/* ------------------------------------------------------------ cat.Regla
   Los códigos deben existir para que LKP_Regla encuentre coincidencia; en FAOSTAT
   la salida No Match de LKP_Regla no está conectada, así que un código ausente
   haría que la fila se descarte. */
MERGE cat.Regla AS t
USING (VALUES
    (N'EVA', N'EVA-DUP', 'DUPLICADO', N'Fila duplicada por (CodigoMunicipioDane, CodigoCultivo, DesagregacionCultivo, Anio, Periodo)', N'Se conserva la primera ocurrencia; el resto va a revisión', N'v1'),
    (N'EVA', N'EVA-CONV', 'ERROR_CONVERSION', N'Valor no convertible a número o texto que no cabe en la columna destino', N'Enviar a revisión con el valor original', N'v1'),
    (N'EVA', N'EVA-MUN', 'SIN_COINCIDENCIA', N'CodigoMunicipioDane inexistente en cat.Municipio (DIVIPOLA)', N'Enviar a revisión', N'v1'),
    (N'EVA', N'EVA-DOM', 'DOMINIO', N'Valor negativo en área, producción o rendimiento', N'Enviar a revisión', N'v1'),
    (N'EVA', N'EVA-CONS', 'CONSISTENCIA', N'AreaCosechada mayor que AreaSembrada', N'Enviar a revisión', N'v1'),
    (N'FAOSTAT', N'FAO-DUP', 'DUPLICADO', N'Fila duplicada por (Dataset, CodigoArea, CodigoElemento, CodigoProducto, CodigoAnio, Unidad)', N'Se conserva la primera ocurrencia; el resto va a revisión', N'v1'),
    (N'FAOSTAT', N'FAO-CNV', 'ERROR_CONVERSION', N'Valor no convertible a DECIMAL(20,4)', N'Enviar a revisión con el texto original', N'v1'),
    (N'FAOSTAT', N'FAO-DOM', 'DOMINIO', N'Valor negativo', N'Enviar a revisión', N'v1'),
    (N'FAOSTAT', N'FAO-CNVF', 'ERROR_CONVERSION', N'Código con carácter no representable en la página de códigos 1252 o más largo que la columna destino', N'Enviar a revisión', N'v1')
) AS s (Familia, Codigo, Categoria, Descripcion, Accion, ReglasVersion)
ON t.Familia = s.Familia AND t.Codigo = s.Codigo AND t.ReglasVersion = s.ReglasVersion
WHEN MATCHED THEN UPDATE SET Categoria = s.Categoria, Descripcion = s.Descripcion, Accion = s.Accion, Activa = 1
WHEN NOT MATCHED THEN INSERT (Familia, Codigo, Categoria, Descripcion, Accion, ReglasVersion)
     VALUES (s.Familia, s.Codigo, s.Categoria, s.Descripcion, s.Accion, s.ReglasVersion);
GO

